package com.yadar.app.util

/**
 * قوانین نرمال‌سازی متن (بند ۳۸ و ۳۹ سند پروژه).
 *
 * نکته مهم: این کلاس هرگز متن اصلی کاربر را که در ستون `text` ذخیره می‌شود
 * تغییر نمی‌دهد. خروجی [forSearch] فقط برای ساخت ستون جداگانه `normalizedText`
 * استفاده می‌شود که مخصوص جست‌وجو است، نه نمایش.
 */
object TextNormalizer {

    private const val ZERO_WIDTH_NON_JOINER = '\u200C'

    /**
     * متن ورودی خام کاربر را برای ذخیره آماده می‌کند: فقط فاصله‌های ابتدا/انتهای
     * غیرضروری و فاصله‌های تکراری معمولی (نه نیم‌فاصله) را جمع می‌کند.
     * نیم‌فاصله (ZWNJ) و کاراکترهای «ی»/«ک» فارسی دست‌نخورده باقی می‌مانند.
     */
    fun forStorage(raw: String): String {
        return raw
            .trim()
            .replace(Regex("[ \\t]{2,}"), " ") // چند فاصله معمولی پشت‌سرهم -> یک فاصله
            .replace(Regex("\\n{3,}"), "\n\n") // بیش از دو خط خالی پشت‌سرهم را محدود کن
    }

    /**
     * نسخه‌ای از متن که فقط برای Index جست‌وجو استفاده می‌شود:
     * - «ي» عربی و «ك» عربی به معادل فارسی «ی»/«ک» یکسان‌سازی می‌شوند (فقط برای تطبیق جست‌وجو)
     * - نیم‌فاصله حذف می‌شود تا «می‌خواهم» و «میخواهم» هر دو پیدا شوند
     * - اعراب و علائم تشکیل حذف می‌شوند
     * - حروف کوچک/بزرگ لاتین یکسان می‌شوند
     */
    fun forSearch(raw: String): String {
        return raw
            .replace('ي', 'ی')
            .replace('ك', 'ک')
            .replace(ZERO_WIDTH_NON_JOINER.toString(), " ")
            .replace(Regex("[\\u064B-\\u065F\\u0670]"), "") // اعراب عربی/فارسی (تشدید، فتحه، ...)
            .lowercase()
            .replace(Regex("\\s{2,}"), " ")
            .trim()
    }
}
